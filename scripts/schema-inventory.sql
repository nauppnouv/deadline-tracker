SELECT CONCAT('TRIGGER|',TRIGGER_NAME,'|',EVENT_OBJECT_TABLE,'|',ACTION_TIMING,'|',EVENT_MANIPULATION)
FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE() AND ACTION_STATEMENT IS NOT NULL
UNION ALL
SELECT CONCAT('CHECK|',TABLE_NAME,'|',CONSTRAINT_NAME)
FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE() AND LENGTH(CHECK_CLAUSE)>0
UNION ALL
SELECT CONVERT(CONCAT('CHECKDEF|',TABLE_NAME,'|',CONSTRAINT_NAME,'|',SHA2(CHECK_CLAUSE,256)) USING utf8mb4) COLLATE utf8mb4_bin
FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE()
UNION ALL
SELECT CONCAT('UNIQUE|',TABLE_NAME,'|',INDEX_NAME,'|',GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX))
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE() AND NON_UNIQUE=0
GROUP BY TABLE_NAME,INDEX_NAME
UNION ALL
SELECT CONCAT('FK|',k.TABLE_NAME,'|',k.CONSTRAINT_NAME,'|',GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.ORDINAL_POSITION),'|',
 k.REFERENCED_TABLE_NAME,'|',GROUP_CONCAT(k.REFERENCED_COLUMN_NAME ORDER BY k.ORDINAL_POSITION),'|',r.DELETE_RULE,'|',r.UPDATE_RULE)
FROM information_schema.KEY_COLUMN_USAGE k JOIN information_schema.REFERENTIAL_CONSTRAINTS r
 ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.TABLE_NAME=k.TABLE_NAME AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
WHERE k.TABLE_SCHEMA=DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
GROUP BY k.TABLE_NAME,k.CONSTRAINT_NAME,k.REFERENCED_TABLE_NAME,r.DELETE_RULE,r.UPDATE_RULE
UNION ALL
SELECT CONCAT('NOTNULL|',TABLE_NAME,'|',COLUMN_NAME) FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA=DATABASE() AND IS_NULLABLE='NO'
UNION ALL
SELECT CONCAT('ENGINE|',TABLE_NAME,'|',ENGINE) FROM information_schema.TABLES WHERE TABLE_SCHEMA=DATABASE()
UNION ALL
SELECT CONCAT('GENERATED|',TABLE_NAME,'|',COLUMN_NAME) FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA=DATABASE() AND IS_GENERATED='ALWAYS' AND LENGTH(GENERATION_EXPRESSION)>0
UNION ALL
SELECT CONVERT(CONCAT('GENERATEDDEF|',TABLE_NAME,'|',COLUMN_NAME,'|',COLUMN_TYPE,'|',EXTRA,'|',SHA2(GENERATION_EXPRESSION,256)) USING utf8mb4) COLLATE utf8mb4_bin
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND IS_GENERATED='ALWAYS'
UNION ALL
SELECT CONVERT(CONCAT('TEXTDEF|',TABLE_NAME,'|',COLUMN_NAME,'|',CHARACTER_SET_NAME,'|',COLLATION_NAME) USING utf8mb4) COLLATE utf8mb4_bin
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
 AND TABLE_NAME IN ('app_user','project_group','group_member','task','invitation','task_event','task_comment','task_comment_revision','comment_mention','notification','task_attachment','task_pin','notification_preference','push_preference','push_device','push_delivery','SPRING_SESSION','SPRING_SESSION_ATTRIBUTES')
 AND CHARACTER_SET_NAME IS NOT NULL
UNION ALL
SELECT CONVERT(CONCAT('COLDEF|',TABLE_NAME,'|',COLUMN_NAME,'|',COLUMN_TYPE,'|',DATA_TYPE,'|',
 COALESCE(CAST(CHARACTER_MAXIMUM_LENGTH AS CHAR),'<NULL>'),'|',COALESCE(CAST(NUMERIC_PRECISION AS CHAR),'<NULL>'),'|',
 COALESCE(CAST(NUMERIC_SCALE AS CHAR),'<NULL>'),'|',COALESCE(CAST(DATETIME_PRECISION AS CHAR),'<NULL>'),'|',
 IS_NULLABLE,'|',REPLACE(COALESCE(COLUMN_DEFAULT,'<NULL>'),'|','<PIPE>'),'|',EXTRA) USING utf8mb4) COLLATE utf8mb4_bin
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
 AND TABLE_NAME IN ('app_user','project_group','group_member','task','invitation','task_event','task_comment','task_comment_revision','comment_mention','notification','task_attachment','task_pin','notification_preference','push_preference','push_device','push_delivery','SPRING_SESSION','SPRING_SESSION_ATTRIBUTES')
UNION ALL
SELECT CONVERT(CONCAT('TRIGGERDEF|',TRIGGER_NAME,'|',EVENT_OBJECT_TABLE,'|',ACTION_TIMING,'|',EVENT_MANIPULATION,'|',SHA2(ACTION_STATEMENT,256)) USING utf8mb4) COLLATE utf8mb4_bin
FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE() AND ACTION_STATEMENT IS NOT NULL;
